function buildCsp(hashesActive) {
  // v34.1 fix: Inline `style="…"` attributes are sprinkled across the
  // dynamically-injected DOM (spotlight cards, scroll-to-top, share toolbar,
  // floating TOC, etc). Hash-listing every unique inline style is impractical
  // — they vary at runtime. So style-src KEEPS `'unsafe-inline'` always
  // (low XSS surface — CSS can't run JS). Only script-src moves to hash mode
  // for the real security win against reflected-XSS.
  const scriptSrc = hashesActive
    ? `script-src 'self' ${INLINE_SCRIPT_HASHES.map(h => `'${h}'`).join(' ')} https://www.googletagmanager.com https://www.google-analytics.com https://www.clarity.ms https://*.clarity.ms https://cdn.jsdelivr.net`
    : `script-src 'self' 'unsafe-inline' https://www.googletagmanager.com https://www.google-analytics.com https://www.clarity.ms https://*.clarity.ms https://cdn.jsdelivr.net`;

  const styleSrc = `style-src 'self' 'unsafe-inline' https://fonts.googleapis.com https://cdn.jsdelivr.net`;

  return [
    `default-src 'self'`,
    scriptSrc,
    styleSrc,
    `font-src 'self' https://fonts.gstatic.com data:`,
    // v37.4: tightened from `https:` catchall (any HTTPS source) to explicit
    // allowlist. Keeps Google Maps/Photo CDN + Vercel previews working but
    // blocks arbitrary 3rd-party image embeds (privacy + tracking-pixel defense).
    `img-src 'self' data: blob: https://hsiao.chendermatologist.com https://*.vercel.com https://*.vercel.app https://www.google-analytics.com https://stats.g.doubleclick.net https://www.googletagmanager.com`,
    `connect-src 'self' https://www.google-analytics.com https://*.google-analytics.com https://*.analytics.google.com https://*.clarity.ms https://stats.g.doubleclick.net`,
    `frame-src 'self' https://www.google.com https://www.youtube.com`,
    `frame-ancestors 'self'`,
    `base-uri 'self'`,
    `form-action 'self' mailto:`,
    `object-src 'none'`,
    `manifest-src 'self'`,
    `worker-src 'self'`,
    `require-trusted-types-for 'script'`,
    `trusted-types default hs-policy`,
    `report-uri /api/csp-report`,
    `upgrade-insecure-requests`,
  ].join('; ');
}

export default function middleware(req) {
  const headers = new Headers();
  // Use hash mode if any hashes are populated (means _gen_csp_hashes.py has run)
  const useHashes = INLINE_SCRIPT_HASHES.length > 0;
  // ENFORCE — prefers hashes when available, falls back to 'unsafe-inline'
  headers.set('Content-Security-Policy', buildCsp(useHashes));
  // REPORT-ONLY mirror — always tightest variant for monitoring
  headers.set('Content-Security-Policy-Report-Only', buildCsp(true));
  headers.set('Reporting-Endpoints', 'csp-endpoint="/api/csp-report"');
  headers.set('x-middleware-next', '1');
  return new Response(null, { headers });
}
